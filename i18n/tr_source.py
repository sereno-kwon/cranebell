# 모델 이름 단독 표기
for k, (en, ja) in MODEL.items():
    T.append((k, en, ja))


def auto_rows(keys):
    """ko.json에서 이미지 대체 텍스트(크레인 {모델} {마감})와 마감 표 컬러 칩 줄을 자동으로 번역합니다."""
    have = {k for k, _, _ in T}
    out = []
    models = sorted(MODEL, key=len, reverse=True)
    for k in keys:
        if k in have:
            continue
        m = re.fullmatch(r'(<i style="[^"]*"></i>)(.+)', k)
        if m and m.group(2) in FINISH:
            en, ja = FINISH[m.group(2)]
            out.append((k, m.group(1) + en, m.group(1) + ja)); continue
        m = re.fullmatch(r'크레인 (.+)', k)
        if m:
            rest = m.group(1)
            for mk in models:
                if rest.startswith(mk + ' ') and rest[len(mk) + 1:] in FINISH:
                    fen, fja = FINISH[rest[len(mk) + 1:]]
                    out.append((k, f'Crane {MODEL[mk][0]}, {fen}', f'クレーン {MODEL[mk][1]} {fja}'))
                    break
    return out


def make_json():
    root = pathlib.Path(__file__).resolve().parent
    rows = T + auto_rows(json.loads((root / 'ko.json').read_text()))
    keys = [k for k, _, _ in rows]
    dup = {k for k in keys if keys.count(k) > 1}
    assert not dup, f'duplicate keys: {dup}'
    for i, lang in ((1, 'en'), (2, 'ja')):
        d = {row[0]: row[i] for row in rows}
        (root / f'{lang}.json').write_text(json.dumps(d, ensure_ascii=False, indent=1))
    print(len(rows), 'entries -> en.json, ja.json')


if __name__ == '__main__':
    make_json()
